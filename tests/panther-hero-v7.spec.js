const {test,expect}=require('@playwright/test');
const path=require('node:path');
const MODEL=path.join(process.cwd(),'dist/assets/panther/elegance-panther-kenchoo-mobile-v1.glb');
test('Panther V7 renders genuine GLB and buttons play distinct clips',async({page})=>{
 test.setTimeout(85000);
 await page.route('**/assets/panther/elegance-panther-kenchoo-mobile-v1.glb',route=>route.fulfill({path:MODEL,contentType:'model/gltf-binary'}));
 await page.goto('/pantera-realista.html');
 await expect(page.locator('.brand')).toHaveText('elegance');
 await expect.poll(()=>page.evaluate(()=>Boolean(customElements.get('model-viewer'))),{timeout:30000}).toBeTruthy();
 await expect.poll(()=>page.evaluate(()=>document.querySelector('#panther').loaded),{timeout:40000}).toBeTruthy();
 const clips=await page.locator('#panther').evaluate(el=>[...el.availableAnimations]);
 expect(clips).toEqual(expect.arrayContaining(['panther_original_16s','idle_breathe','roar_short','look_left','look_right','stance_shift']));
 await expect(page.locator('#model-state')).toContainText('47 huesos');
 await page.locator('[data-clip="roar_short"]').click();
 await expect.poll(()=>page.locator('#panther').evaluate(el=>el.animationName)).toBe('roar_short');
 await page.locator('#panther').evaluate(el=>{el.pause();el.currentTime=1.35;});
 await page.waitForTimeout(300);
 const visual=await page.locator('.showroom').screenshot({type:'jpeg',quality:45});
 console.log('ELEGANCE_V7_HERO_ROAR_JPG_BASE64:',visual.toString('base64'));
 await page.locator('[data-clip="look_left"]').click();
 await expect.poll(()=>page.locator('#panther').evaluate(el=>el.animationName)).toBe('look_left');
 await page.locator('[data-clip="idle_breathe"]').click();
 await expect.poll(()=>page.locator('#panther').evaluate(el=>el.animationName)).toBe('idle_breathe');
 await page.locator('#toggle-play').click();
 await expect(page.locator('#toggle-play')).toHaveAttribute('aria-pressed','false');
 await page.locator('#reset-view').click();
 await expect(page.locator('#toggle-play')).toHaveAttribute('aria-pressed','true');
});
test('V7 is responsive and original showroom identity remains intact',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/pantera-realista.html');
 await expect(page.locator('.brand')).toHaveText('elegance');
 await expect(page.locator('#panther')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await expect(page.locator('a[href*="sketchfab.com/3d-models/black-panther"]')).toHaveCount(1);
 await page.goto('/showroom.html');
 await expect(page.locator('a[href="./pantera-ice-v8.html"]')).toBeVisible();
 await expect(page.locator('.brand')).toHaveText('elegance');
});

const {test,expect}=require('@playwright/test');
const path=require('node:path');
const compiled=path.join(process.cwd(),'dist/assets/panther/elegance-panther-ice-gallery-v8.glb');
test('V9 preserves approved screenshot by default and enables actual 3D inside the SAME dashboard',async({page})=>{
 test.setTimeout(110000);
 await page.route('**/assets/panther/elegance-panther-ice-gallery-v8.glb',r=>r.fulfill({path:compiled,contentType:'model/gltf-binary'}));
 await page.goto('/showroom.html');
 await expect(page.locator('.brand')).toHaveText('elegance');
 await expect(page.locator('#view')).not.toHaveClass(/real-3d/);
 await expect(page.locator('#scene-layer')).toBeVisible();
 await expect(page.locator('#real3d-toggle')).toHaveAttribute('aria-pressed','false');
 await page.locator('#real3d-toggle').click();
 await expect(page.locator('#view')).toHaveClass(/real-3d/);
 await expect(page.locator('#scene-3d-frame')).toHaveAttribute('src','./scene-ice-embed.html');
 await expect.poll(()=>page.frameLocator('#scene-3d-frame').locator('#panther').evaluate(el=>el.loaded),{timeout:55000}).toBeTruthy();
 await expect(page.locator('#scene-status')).toContainText('47 huesos');
 await expect(page.locator('#real3d-toggle')).toHaveAttribute('aria-pressed','true');
 await page.locator('#roar').click();
 await expect.poll(()=>page.frameLocator('#scene-3d-frame').locator('#panther').evaluate(el=>el.animationName)).toBe('roar_short');
 await page.locator('[data-preset="night"]').click();
 await expect(page.frameLocator('#scene-3d-frame').locator('body')).toHaveClass(/night/);
 await page.locator('#real3d-toggle').click();
 await expect(page.locator('#view')).not.toHaveClass(/real-3d/);
 await expect(page.locator('#scene-layer')).toBeVisible();
 await expect(page.locator('#scene-3d-frame')).not.toHaveAttribute('src',/.+/);
 await expect(page.locator('#real3d-toggle')).toHaveAttribute('aria-pressed','false');
});
test('V9 embeds mobile GLB without horizontal overflow and can revert to original',async({page})=>{
 test.setTimeout(105000);
 await page.route('**/assets/panther/elegance-panther-ice-gallery-v8.glb',r=>r.fulfill({path:compiled,contentType:'model/gltf-binary'}));
 await page.setViewportSize({width:390,height:844});
 await page.goto('/showroom.html');
 await expect(page.locator('#real3d-toggle')).toBeVisible();
 await page.locator('#real3d-toggle').click();
 await expect.poll(()=>page.frameLocator('#scene-3d-frame').locator('#panther').evaluate(el=>el.loaded),{timeout:55000}).toBeTruthy();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await expect(page.locator('#catalog-drawer')).toBeHidden();
 await page.locator('#real3d-toggle').click();
 await expect(page.locator('#scene-layer')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
});
